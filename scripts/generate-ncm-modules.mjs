import fs from 'fs';
import path from 'path';

const moduleDir = path.resolve('node_modules/netease-cloud-music-api-alger/module');
const files = fs.readdirSync(moduleDir).filter(f => f.endsWith('.js'));

const specialRoutes = {
  'daily_signin.js': '/daily_signin',
  'fm_trash.js': '/fm_trash',
  'personal_fm.js': '/personal_fm',
};

const parseRoute = (fileName) => {
  if (specialRoutes[fileName]) return specialRoutes[fileName];
  return `/${fileName.replace(/\.js$/i, '').replace(/_/g, '/')}`;
};

let supportedCount = 0;
const modulesMap = {};

for (const file of files) {
  let content = fs.readFileSync(path.join(moduleDir, file), 'utf-8');

  // Skip files that require node-specific things like fs/path/upload/music-metadata/qrcode
  if (
    content.includes("require('fs')") ||
    content.includes('require("fs")') ||
    content.includes("require('path')") ||
    content.includes('require("path")') ||
    content.includes("require('music-metadata')") ||
    content.includes("require('../plugins/upload')") ||
    content.includes("require('../plugins/songUpload')") ||
    content.includes("require('xml2js')")
  ) {
    continue;
  }

  // Remove require statements that we provide globally in the file
  content = content.replace(/const\s+createOption\s*=\s*require\([^)]+\);?/g, '');
  content = content.replace(/const\s*\{\s*resourceTypeMap\s*\}\s*=\s*require\([^)]+\);?/g, '');
  content = content.replace(/const\s+CryptoJS\s*=\s*require\([^)]+\);?/g, '');
  content = content.replace(/const\s*\{\s*toBoolean\s*\}\s*=\s*require\([^)]+\);?/g, '');
  content = content.replace(/const\s+md5\s*=\s*require\([^)]+\);?/g, '');

  // Extract function after module.exports = 
  const exportMatch = content.match(/module\.exports\s*=\s*([\s\S]+)$/);
  if (!exportMatch) {
    continue;
  }

  const funcBody = exportMatch[1].trim();
  const route = parseRoute(file);
  modulesMap[route] = funcBody;
  supportedCount++;
}

// Module patches for direct mobile execution
modulesMap['/like'] = `(query, request) => {
  query.like = query.like === false || query.like === 'false' ? false : true;
  const data = {
    alg: 'itembased',
    trackId: query.id,
    like: query.like,
    time: '3',
  };
  return request(\`/api/radio/like\`, data, createOption(query, 'eapi')).catch(() => {
    return request(\`/api/radio/like\`, data, createOption(query, 'weapi'));
  });
}`;

modulesMap['/likelist'] = `(query, request) => {
  const data = {
    uid: query.uid,
  };
  return request(\`/api/song/like/get\`, data, createOption(query, 'eapi')).catch(() => {
    return request(\`/api/song/like/get\`, data, createOption(query, 'weapi'));
  });
}`;

modulesMap['/login/qr/key'] = `(query, request) => {
  const data = {
    type: 1,
  };
  return request(\`/api/login/qrcode/unikey\`, data, createOption(query, 'weapi')).then(result => ({
    status: 200,
    body: {
      data: result.body,
      code: 200,
    },
    cookie: result.cookie,
  }));
}`;

modulesMap['/login/qr/check'] = `(query, request) => {
  const data = {
    key: query.key,
    type: 1,
  };
  return request(\`/api/login/qrcode/client/login\`, data, createOption(query, 'weapi')).then(result => ({
    status: 200,
    body: {
      ...result.body,
      cookie: Array.isArray(result.cookie) ? result.cookie.join(';') : (result.cookie || ''),
    },
    cookie: result.cookie,
  })).catch(() => ({
    status: 200,
    body: { code: 800 },
  }));
}`;

modulesMap['/user/account'] = `(query, request) => {
  const data = {};
  return request(\`/api/nuser/account/get\`, data, createOption(query, 'weapi')).then(async (result) => {
    if (result.body && !result.body.profile && !result.body.account) {
      try {
        const fallback = await request(\`/api/w/nuser/account/get\`, data, createOption(query, 'weapi'));
        if (fallback.body && (fallback.body.profile || fallback.body.account)) {
          return fallback;
        }
      } catch {}
    }
    return result;
  });
}`;

console.log(`Successfully parsed ${supportedCount} of ${files.length} modules.`);

const outputHeader = `/* eslint-disable */
// @ts-nocheck
// Auto-generated by scripts/generate-ncm-modules.mjs
// Bundles NetEase Cloud Music API modules directly for client-side execution
import CryptoJS from 'crypto-js';

const resourceTypeMap = {
  "0": "R_SO_4_",
  "1": "R_MV_5_",
  "2": "A_PL_0_",
  "3": "R_AL_3_",
  "4": "A_DJ_1_",
  "5": "R_VI_62_",
  "6": "A_EV_2_",
  "7": "A_DR_14_"
};

const toBoolean = (val) => {
  if (typeof val === 'boolean') return val;
  if (val === '') return val;
  return val === 'true' || val === '1';
};

const md5 = (str) => CryptoJS.MD5(str).toString();

const createOption = (query, crypto = '') => {
  return {
    crypto: query?.crypto || crypto || '',
    cookie: query?.cookie,
    ua: query?.ua || '',
    proxy: query?.proxy,
    realIP: query?.realIP,
    e_r: query?.e_r || undefined,
    domain: query?.domain || '',
    checkToken: query?.checkToken || false,
  };
};

export const ncmModules = {};
`;

let outputCode = outputHeader + '\n';
for (const [route, funcStr] of Object.entries(modulesMap)) {
  outputCode += `ncmModules['${route}'] = ${funcStr};\n`;
}

const outDir = path.resolve('src/renderer/api/ncmDirect');
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

fs.writeFileSync(path.join(outDir, 'generatedModules.ts'), outputCode, 'utf-8');
console.log('Saved generatedModules.ts to', path.join(outDir, 'generatedModules.ts'));
